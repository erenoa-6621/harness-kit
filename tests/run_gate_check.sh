#!/usr/bin/env bash
# tools/gate_check.sh の回帰スイート。
#
# なぜ要るか:
#   gate_check.sh は「その一手が人間ゲートか」を機械で判定する道具である。
#   **ここが静かに壊れると、人間ゲートを踏み越えたまま緑を見る。**
#   denylist 型の検査は実測で穴を出し続けるので、**判定の分かれ目に検体を置く。**
#
#   **裁量側（0）の検体を必ず同じだけ置く。** 過検知＝「内部の作業まで人間ゲートに送る」であり、
#   それは安全側の失敗ではない。人間ゲートが開発を邪魔している状態そのものである。
#   止める側だけ測ると、その失敗形は永久に見つからない。
#
# 終了コードの意味（gate_check.sh 本体と同じ）:
#   0 = 裁量 / 1 = 人間ゲート / 2 = 判定できない（人間ゲート扱い）
#
# 【このスイートが保証すること・しないこと】
#   保証する : 既知の型について、判定が今日と同じであること（退行の検知）
#   保証しない: gate_check.sh の網羅性。あれは denylist であって境界ではない。
#              **緑になっても「すべての外向き操作を捕まえる」証明にはならない。**
#
# 検体は $HOME に依存させない。`~/project/...` は**展開せずに文字列のまま**渡す。
# "$HOME/..." と書くと、HOME=/tmp/fakehome の環境で「/tmp 配下＝裁量」に化けて検体の意味が反転する。
set -uo pipefail
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
GATE="$HERE/../tools/gate_check.sh"
pass=0; fail=0

# **人間ゲートが素の環境で開いていた**実測がある：
#   `bash tools/gate_check.sh "本番サーバへ反映する"` は 通常 rc=1（人間ゲート）／
#   cron 相当の素の環境（LANG 無し）で rc=0（裁量）。
#   原因は多バイトを含む否定文字クラス `[^。]` がバイト環境で壊れること
#   （`サ`=E3 82 B5 と `。`=E3 80 82 がバイトを共有し `[^。]*` が跨げない）。
#   cron も CI も LANG を持たない。**机上の話ではない。**
#   → **全検体を「通常環境」と「素の環境」の両方で撃ち、判定が一致することまで見る。**
#     片方でしか撃たないなら、環境で開くゲートに気づけない。
ENVCHECK="${GATE_ENVCHECK:-1}"
# **`GATE_ENVCHECK=0` を置くだけで環境比較が無音で死ぬ**と、修正前の fail-open 版でも全緑になる。
#   逃がし口は残すが、黙らせない。
if [ "$ENVCHECK" != "1" ]; then
  echo "  🔴 GATE_ENVCHECK=$ENVCHECK：環境比較を無効にして走らせている。この実行の緑は根拠にならない"
  ENVCHECK_OFF=1
fi
_bare() { env -i HOME="${HOME:-/tmp}" PATH=/usr/bin:/bin bash "$GATE" "$1" >/dev/null 2>&1; }

run() {  # 操作の説明文 期待exit 説明
  local what="$1" want="$2" note="$3" got got_bare
  bash "$GATE" "$what" >/dev/null 2>&1
  got=$?
  if [ "$ENVCHECK" = "1" ]; then
    _bare "$what"; got_bare=$?
    if [ "$got_bare" -ne "$got" ]; then
      fail=$((fail+1))
      printf '  NG %s（**環境で判定が変わる**）\n     what: %s\n     通常=%s 素の環境=%s\n' "$note" "$what" "$got" "$got_bare"
      return
    fi
  fi
  if [ "$got" -eq "$want" ]; then pass=$((pass+1))
  else
    fail=$((fail+1))
    printf '  NG %s\n     what: %s\n     want=%s got=%s  [%s]\n' "$note" "$what" "$want" "$got" "$(basename "$GATE")"
  fi
}

# 出力の中身まで見る検体。**exit コードだけ見る検査では取り逃す失敗があるため足した**
# （裁量の2条件を出力から削る変異を撃っても、exit だけ見る run() は緑のままだった）。
#
# なぜ中身を見る必要があるのか:
#   配線の裁量は**条件つき**である（①検査が緑 ②即時停止できる経路）。
#   条件を出力しない実装は「許可だけを返す機械」になり、条件を静かに落とす。
#   **条件を落としても exit は 0 のままなので、exit だけ見る検査では永久に見つからない。**
run_out() {  # 操作の説明文 期待exit 出力に必ず含まれる文字列 説明
  local what="$1" want="$2" needle="$3" note="$4" got out
  out=$(bash "$GATE" "$what" 2>&1); got=$?
  if [ "$got" -eq "$want" ] && printf '%s' "$out" | grep -qF -- "$needle"; then pass=$((pass+1))
  else
    fail=$((fail+1))
    printf '  NG %s\n     what: %s\n     want=%s got=%s / needle=%s\n     out: %s\n' \
      "$note" "$what" "$want" "$got" "$needle" "$out"
  fi
}

